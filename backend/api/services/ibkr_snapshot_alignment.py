"""Bounded complete-account/day alignment, with no collector or endpoint invocation.

Integration contract:
* The source adapter must prove authority/completeness for ONE statement/account/day,
  resolve securities to stable identities (never descriptions/symbols alone), and
  retain explicit zero cash evidence before the collector omits zero-valued rows.
* Read BOTH complete account/day sets with ``read_snapshot_rows`` and bind
  ``read_snapshot_numeric_scales`` in the evidence. Supply whole-row
  fingerprints and ownership attestations bound to those rows. The holdings table
  has no provenance column: account membership or a symbol match is NOT ownership.
  Attestations must come from verified source lineage/publication evidence. Unknown
  lineage blocks; independent manual rows are preserved. A historical candidate
  exception requires a separate row-bound proof AND exact historical approval.
* Replace history UPSERT-only writes with a source_sync plan/apply inside the
  collector's existing transaction (``within_transaction=True``). Do not follow it
  with the legacy account/day DELETE/UPSERT writer. Do not label mixed publication
  dates as the source date. Mapping to a different portfolio date is outside this
  helper. Source-owned authorization must be generated by a trusted sync boundary,
  not an HTTP caller or the report itself. Default mode is historical and dry-run.
  Nested live apply requires READ COMMITTED; an earlier repeatable-read snapshot
  could otherwise conceal rows inserted before this helper acquires its locks.
  Propagate any failure to abort the enclosing sync transaction; do not commit
  unrelated partial collector writes after catching an alignment failure.
* Explicit historical apply requires an independently approved plan digest. No
  CLI, connection factory, DDL, migration, report refresh, or automatic apply exists.
  Attestation dictionaries are evidence bindings, NOT authentication/permission.
  Historical scope is DELETE ONLY: preserve every matched row byte-for-byte,
  never backfill missing rows or canonicalize prices/cost/quantity/metadata.
  A different historical financial correction requires a separately scoped change.
"""
from __future__ import annotations

from copy import deepcopy
from datetime import date, datetime, timedelta, timezone
from decimal import Decimal, InvalidOperation, ROUND_HALF_UP, localcontext
import hashlib
import json
import re
from typing import Any, Literal, overload
import xml.etree.ElementTree as ET

from psycopg2 import sql
from psycopg2.extensions import TRANSACTION_STATUS_IDLE, TRANSACTION_STATUS_INTRANS
from psycopg2.extras import RealDictCursor

HISTORY = "pams_ibkr_position_history"
HOLDINGS = "pams_holdings_snapshot"
TABLES = (HISTORY, HOLDINGS)
SCHEMA = "public"
MAX_ROWS = 10000
FIELDS = ("account_code", "symbol", "name", "asset_liability", "currency",
          "major_category", "minor_category", "market_value", "cost", "quantity",
          "buy_price", "current_price", "as_of")
NUMBERS = {"market_value", "cost", "quantity", "buy_price", "current_price"}
SHA256 = re.compile(r"[0-9a-f]{64}", re.ASCII)
MAX_XML_BYTES = 32 * 1024 * 1024


class AlignmentBlocked(ValueError):
    """Invalid, ambiguous, incomplete, unauthorized or changed snapshot evidence."""


def _canonical(value: Any) -> Any:
    # Same evidence format as ibkr_lineage_rehearsal, without importing collectors
    # (and their scheduler/calendar dependencies) into a standalone apply helper.
    if isinstance(value, datetime):
        text = value.isoformat()
        if value.microsecond:
            fraction = f".{value.microsecond:06d}"
            text = text.replace(fraction, fraction.rstrip("0"), 1)
        return ["text", text]
    if isinstance(value, date):
        return ["text", value.isoformat()]
    if isinstance(value, (int, float, Decimal)) and not isinstance(value, bool):
        number = Decimal(str(value))
        _require(number.is_finite(), "Nonfinite fingerprint input")
        text = format(number, "f")
        return ["number", (text.rstrip("0").rstrip(".") if "." in text else text) if number else "0"]
    if isinstance(value, dict):
        return ["object", [[key, _canonical(value[key])] for key in sorted(value)]]
    if isinstance(value, (list, tuple)):
        return ["array", [_canonical(item) for item in value]]
    if value is None or isinstance(value, (bool, str)):
        return ["text" if isinstance(value, str) else type(value).__name__, value]
    raise TypeError(type(value).__name__)


def fingerprint(rows: list[dict]) -> str:
    """Order-independent whole rows; preserve duplicates, precision, and metadata."""
    encoded = sorted(json.dumps(_canonical(row), sort_keys=True, ensure_ascii=True) for row in rows)
    return hashlib.sha256(json.dumps(encoded, ensure_ascii=True).encode()).hexdigest()


def _require(condition: Any, message: str) -> None:
    if not condition:
        raise AlignmentBlocked(message)


def _text(value: Any) -> bool:
    return isinstance(value, str) and 0 < len(value.strip()) <= 500


def _day(value: Any) -> str:
    _require(not isinstance(value, datetime), "Date, not timestamp, required")
    try:
        return date.fromisoformat(str(value)).isoformat()
    except (TypeError, ValueError) as exc:
        raise AlignmentBlocked("Invalid snapshot date") from exc


def _digest(value: Any) -> bool:
    return isinstance(value, str) and SHA256.fullmatch(value) is not None


@overload
def _number(value: Any, *, nullable: Literal[False], scale: int = 10) -> Decimal: ...


@overload
def _number(value: Any, *, nullable: Literal[True], scale: int = 10) -> Decimal | None: ...


@overload
def _number(value: Any, *, nullable: bool, scale: int = 10) -> Decimal | None: ...


def _number(value: Any, *, nullable: bool, scale: int = 10) -> Decimal | None:
    if value is None and nullable:
        return None
    _require(value is not None and not isinstance(value, bool), "Missing numeric evidence")
    try:
        with localcontext() as ctx:
            ctx.prec = 60
            number = Decimal(str(value))
            _require(number.is_finite() and abs(number) < Decimal("1e18"), "Invalid numeric evidence")
            result = number.quantize(Decimal(1).scaleb(-scale), rounding=ROUND_HALF_UP)
            _require(abs(result) < Decimal("1e18"), "Numeric overflow")
            return result
    except (InvalidOperation, ValueError) as exc:
        raise AlignmentBlocked("Invalid numeric evidence") from exc


def _source_number(value: Any) -> Decimal:
    _number(value, nullable=False)
    return Decimal(str(value))


def _identity(identity: Any, kind: Any, currency: Any) -> tuple[str, str]:
    _require(isinstance(currency, str) and re.fullmatch(r"[A-Z]{3}", currency, re.ASCII),
             "Explicit native currency required")
    _require(kind in ("cash", "position"), "Missing row kind")
    if kind == "cash":
        _require(identity == "cash:" + currency, "Invalid cash identity")
    else:
        _require(_text(identity) and re.fullmatch(r"(?:asset|conid|isin):[^\s:]+", identity),
                 "Stable resolved security identity required")
    return identity, currency


def _scope(evidence: dict) -> dict:
    _require(evidence.get("source") == "ibkr_flex", "Unsupported source")
    for field in ("account_code", "source_account_id", "source_key", "authority_reference"):
        _require(_text(evidence.get(field)), "Missing source scope/authority")
    _require(_digest(evidence.get("source_sha256")), "Source fingerprint required")
    _require(evidence.get("authoritative") is True and evidence.get("complete_account") is True,
             "Authoritative complete account snapshot required")
    _require(type(evidence.get("statement_count")) is int and evidence["statement_count"] == 1,
             "Unique source statement required")
    for section in ("positions_section", "cash_section"):
        _require(evidence.get(section) in ("complete", "empty"), "Missing or partial section")
    scales = evidence.get("numeric_scales", {})
    _require(set(scales) == set(TABLES), "Both table numeric contracts required")
    for table in TABLES:
        _require(set(scales[table]) == NUMBERS
                 and all(type(n) is int and 0 <= n <= 10 for n in scales[table].values()),
                 "Unsupported numeric storage contract")
    return {"account_code": evidence["account_code"], "source_account_id": evidence["source_account_id"],
            "as_of": _day(evidence.get("as_of"))}


def _in_scope(row: dict, scope: dict) -> bool:
    return row.get("account_code") == scope["account_code"] and _day(row.get("as_of")) == scope["as_of"]


def _payload(row: dict, table: str, scope: dict, scales: dict) -> dict:
    _require(_in_scope(row, scope), "Cross-account/date row")
    _require(row.get("source_account_id") == scope["source_account_id"], "Cross-source row")
    _require(set(FIELDS) <= row.keys(), "Incomplete desired row")
    data = {key: row[key] for key in FIELDS}
    for key in ("name", "symbol", "asset_liability", "major_category", "minor_category"):
        _require(_text(data[key]), "Missing desired field")
    _require(len(data["name"]) <= 200 and len(data["symbol"]) <= 100, "Oversized desired identity")
    data["as_of"] = scope["as_of"]
    for key in NUMBERS:
        data[key] = _number(data[key], nullable=False, scale=scales[table][key])
    if table == HISTORY:
        data["source_account_id"] = scope["source_account_id"]
    return data


def _currency_set(evidence: dict, field: str) -> set[str]:
    values = evidence.get(field)
    _require(isinstance(values, (list, tuple)) and len(values) <= MAX_ROWS, "Cash coverage required")
    assert isinstance(values, (list, tuple))
    _require(all(isinstance(c, str) and re.fullmatch(r"[A-Z]{3}", c, re.ASCII) for c in values),
             "Invalid cash coverage")
    _require(len(values) == len(set(values)), "Duplicate cash coverage")
    return set(values)


def source_snapshot_from_xml(*, source_bytes: bytes, account_code: str, source_account_id: str,
                             as_of: date | str, source_key: str, authority_reference: str,
                             numeric_scales: dict, complete_account: bool = False,
                             authoritative: bool = False) -> tuple[dict, list[dict]]:
    """Extract ONE daily source set, never infer ownership of existing database rows.

    The trusted adapter caller must independently attest that the query is the
    authoritative complete account query (not a symbol/model-filtered export).
    XML structure alone cannot prove this. Exact existing-row ownership proofs
    remain mandatory even when this extraction succeeds, especially for extras.
    """
    _require(isinstance(source_bytes, bytes) and len(source_bytes) <= MAX_XML_BYTES, "Unsupported XML size")
    _require(not re.search(br"<!\s*(?:DOCTYPE|ENTITY)\b", source_bytes, re.IGNORECASE)
             and b"\x00" not in source_bytes, "Unsupported XML declaration/encoding")
    try:
        root = ET.fromstring(source_bytes)
    except (ET.ParseError, ValueError) as exc:
        raise AlignmentBlocked("Invalid XML") from exc
    for node in root.iter():
        node.tag = node.tag.rsplit("}", 1)[-1]
    day = _day(as_of)
    source_day = day.replace("-", "")
    statements = list(root.iter("FlexStatement"))
    _require(len(statements) <= 1000, "Statement bound exceeded")
    selected = [s for s in statements if s.get("accountId") == source_account_id
                and s.get("toDate") in (day, source_day)]
    _require(len(selected) == 1, "Unique account/day source statement required")
    statement = selected[0]
    _require(statement.get("fromDate") in (day, source_day), "Daily, not period-end, snapshot required")
    members = set(statement.iter())
    parents = {child: node for node in root.iter() for child in node}
    ancestor = parents.get(statement)
    while ancestor is not None:
        for field in ("accountId", "acctId"):
            _require(not ancestor.get(field) or ancestor.get(field) == source_account_id, "Conflicting ancestor account")
        ancestor = parents.get(ancestor)
    all_members = {node for s in statements for node in s.iter()}
    for node in root.iter():
        if node.tag in ("OpenPosition", "CashReportCurrency"):
            _require(node in all_members, "Orphan source row")
    for node in members:
        # Conflicting ancestor scopes (including model partitions) are not ignored.
        for field in ("accountId", "acctId"):
            _require(not node.get(field) or node.get(field) == source_account_id, "Conflicting source account")
        _require(not node.get("model"), "Partial model snapshot")
    sections = {}
    for tag in ("OpenPositions", "CashReport"):
        containers = list(statement.iter(tag))
        _require(len(containers) == 1 and containers[0] in list(statement), "Missing/ambiguous source section")
        for field in ("fromDate", "toDate", "reportDate"):
            _require(not containers[0].get(field) or containers[0].get(field) in (day, source_day), "Conflicting section date")
        sections[tag] = containers[0]
    info = list(statement.iter("AccountInformation"))
    _require(len(info) == 1 and info[0].get("accountId") == source_account_id, "Account authority scope required")
    rows: list[dict] = []
    identities: set[tuple[str, str]] = set()
    position_members = set(sections["OpenPositions"].iter())
    cash_members = set(sections["CashReport"].iter())
    currencies: set[str] = set()
    zeros: set[str] = set()
    source_row_count = 0
    for node in statement.iter():
        if node.tag not in ("OpenPosition", "CashReportCurrency"):
            continue
        source_row_count += 1
        _require(source_row_count <= MAX_ROWS, "Source row bound exceeded")
        attrs = node.attrib
        _require(attrs.get("accountId") == source_account_id, "Unbound source row account")
        ancestor = parents.get(node)
        while ancestor is not None and ancestor is not statement:
            for field in ("fromDate", "toDate", "reportDate"):
                _require(not ancestor.get(field) or ancestor.get(field) in (day, source_day), "Conflicting ancestor date")
            ancestor = parents.get(ancestor)
        currency = attrs.get("currency", "")
        if node.tag == "CashReportCurrency":
            _require(node in cash_members and attrs.get("toDate") in (day, source_day)
                     and attrs.get("fromDate") in (day, source_day), "Cash row outside daily section")
            if currency == "BASE_SUMMARY":
                continue
            _require(attrs.get("levelOfDetail") == "Currency", "Native cash detail required")
            key = _identity("cash:" + currency, "cash", currency)
            _require(currency not in currencies, "Duplicate native cash currency")
            currencies.add(currency)
            value = _source_number(attrs.get("endingCash"))
            if value == 0:
                zeros.add(currency)
                continue
            row = {"resolved_identity": key[0], "kind": "cash", "symbol": "CASH_" + currency,
                   "name": "Cash " + currency, "market_value": value, "quantity": value,
                   "cost": value, "buy_price": Decimal(1), "current_price": Decimal(1),
                   "major_category": "\u73b0\u91d1" if value > 0 else "\u501f\u6b3e",
                   "minor_category": "\u73b0\u91d1/\u6d3b\u671f" if value > 0 else "\u501f\u6b3e"}
        else:
            _require(node in position_members and attrs.get("reportDate") in (day, source_day),
                     "Position row outside daily section")
            _require(attrs.get("levelOfDetail") == "SUMMARY", "Complete summary positions required")
            key = _identity("conid:" + attrs.get("conid", ""), "position", currency)
            _require(key not in identities, "Duplicate source resolved identity")
            identities.add(key)
            quantity = _source_number(attrs.get("position"))
            value = _source_number(attrs.get("positionValue", attrs.get("marketValue")))
            if "positionValue" in attrs and "marketValue" in attrs:
                _require(value == _source_number(attrs["marketValue"]), "Conflicting native position values")
            if quantity == 0 and value == 0:
                continue
            _require(_text(attrs.get("symbol")) and _text(attrs.get("description")), "Position display identity required")
            symbol, description = attrs["symbol"].upper(), attrs["description"]
            name = description if description.upper() == symbol else symbol + " - " + description
            row = {"resolved_identity": key[0], "kind": "position", "symbol": symbol,
                   "name": " ".join(name.split())[:180], "market_value": value, "quantity": quantity,
                   "cost": _source_number(attrs.get("costBasisMoney")),
                   "buy_price": _source_number(attrs.get("costBasisPrice")),
                   "current_price": _source_number(attrs.get("markPrice")),
                   "major_category": "\u7f8e\u80a1", "minor_category": "\u7f8e\u80a1\u57fa\u91d1"}
        rows.append({**row, "account_code": account_code, "source_account_id": source_account_id,
                     "as_of": day, "currency": currency,
                     "asset_liability": "\u8d44\u4ea7" if value >= 0 else "\u8d1f\u503a"})
    evidence = {"source": "ibkr_flex", "account_code": account_code, "source_account_id": source_account_id,
                "as_of": day, "source_key": source_key, "authority_reference": authority_reference,
                "source_sha256": hashlib.sha256(source_bytes).hexdigest(), "statement_count": 1,
                "authoritative": authoritative, "complete_account": complete_account,
                "positions_section": "complete" if any(r["kind"] == "position" for r in rows) else "empty",
                "cash_section": "complete" if currencies - zeros else "empty", "cash_currencies": sorted(currencies),
                "zero_cash_currencies": sorted(zeros), "numeric_scales": deepcopy(numeric_scales)}
    _scope(evidence)
    return evidence, rows


def plan_snapshot_alignment(*, evidence: dict, desired_rows: list[dict],
                            before_rows: dict[str, list[dict]], before_sha256: dict[str, str],
                            ownership: list[dict], mode: str = "historical",
                            candidate_proofs: list[dict] | None = None) -> dict:
    """Plan exact-set changes, raising AlignmentBlocked instead of guessing.

    Every existing row needs one ownership record: table, id, row_sha256,
    resolved_identity, kind, provenance (source_managed/manual/unknown),
    source_account_id, source_sha256 and reference. Manual records need only the
    first six fields and reference. Historical candidate proofs additionally bind
    table/id/row_sha256/source_sha256/source_account_id/reference to this report.
    A full-row hash includes IDs and metadata; source projections use NUMERIC(28,10).
    """
    evidence, desired_rows, before_rows = deepcopy((evidence, desired_rows, before_rows))
    ownership, candidate_proofs = deepcopy((ownership, candidate_proofs or []))
    scope = _scope(evidence)
    _require(mode in ("historical", "source_sync"), "Invalid alignment mode")
    _require(set(before_rows) == set(TABLES) == set(before_sha256), "Both complete table sets required")
    _require(len(desired_rows) <= MAX_ROWS and len(ownership) <= 2 * MAX_ROWS
             and len(candidate_proofs) <= 2 * MAX_ROWS, "Snapshot bound exceeded")
    _require(mode == "historical" or not candidate_proofs, "Historical candidates require historical approval")
    desired_rows.sort(key=lambda row: (str(row.get("resolved_identity")), str(row.get("currency"))))
    ownership.sort(key=lambda row: (str(row.get("table")), str(row.get("id"))))
    candidate_proofs.sort(key=lambda row: (str(row.get("table")), str(row.get("id"))))
    coverage = _currency_set(evidence, "cash_currencies")
    zeros = _currency_set(evidence, "zero_cash_currencies")
    _require(zeros <= coverage, "Zero cash outside declared currency coverage")
    desired: dict[tuple[str, str], dict] = {}
    names: set[str] = set()
    cash: set[str] = set()
    positions = 0
    for row in desired_rows:
        key = _identity(row.get("resolved_identity"), row.get("kind"), row.get("currency"))
        _require((row.get("symbol") == "CASH_" + key[1]) == (row["kind"] == "cash"), "Cash kind/identity conflict")
        _payload(row, HISTORY, scope, evidence["numeric_scales"])
        _require(key not in desired and row["name"] not in names, "Duplicate identity/name in source snapshot")
        desired[key] = row
        names.add(row["name"])
        if row["kind"] == "cash":
            _require(_number(row["market_value"], nullable=False) != 0,
                     "Zero cash must be explicit omission evidence, not a stored row")
            cash.add(row["currency"])
        else:
            positions += 1
    _require((positions == 0) == (evidence["positions_section"] == "empty"), "Position section/count mismatch")
    _require((not cash) == (evidence["cash_section"] == "empty"), "Cash section/count mismatch")
    _require(not cash & zeros and cash | zeros == coverage, "Missing/ambiguous native cash evidence")
    proofs: dict[tuple[str, Any], dict] = {}
    candidates: dict[tuple[str, Any], dict] = {}
    for records, proof_map in ((ownership, proofs), (candidate_proofs, candidates)):
        for proof in records:
            proof_key = proof.get("table"), proof.get("id")
            _require(proof_key[0] in TABLES and type(proof_key[1]) is int and proof_key[1] > 0 and proof_key not in proof_map,
                     "Invalid/duplicate row proof")
            _require(_text(proof.get("reference")) and _digest(proof.get("row_sha256")), "Unbound row proof")
            assert isinstance(proof_key[0], str)
            proof_map[(proof_key[0], proof_key[1])] = proof
    operations = []
    missing_source_rows: dict[str, list[list[str]]] = {}
    projected: dict[str, list[dict]] = {}
    seen_proofs: set[tuple[str, Any]] = set()
    for table in TABLES:
        rows = sorted(before_rows[table], key=lambda row: row.get("id", 0))
        _require(len(rows) <= MAX_ROWS and all(_in_scope(row, scope) for row in rows), "Incomplete/broad before scope")
        _require(_digest(before_sha256[table]) and fingerprint(rows) == before_sha256[table], "Before-state hash mismatch")
        existing: dict[tuple[str, str], tuple[dict, dict, bool]] = {}
        seen_ids: set[int] = set()
        seen_names: set[str] = set()
        for row in rows:
            row_id = row.get("id")
            _require(type(row_id) is int and row_id > 0 and row_id not in seen_ids, "Invalid/duplicate database row")
            assert isinstance(row_id, int)
            _require(_text(row.get("name")) and row["name"] not in seen_names, "Ambiguous database name")
            seen_ids.add(row_id)
            seen_names.add(row["name"])
            pk = table, row_id
            proof = proofs.get(pk, {})
            _require(proof.get("row_sha256") == fingerprint([row]), "Missing/stale ownership proof")
            seen_proofs.add(pk)
            key = _identity(proof.get("resolved_identity"), proof.get("kind"), row.get("currency"))
            _require((row.get("symbol") == "CASH_" + key[1]) == (proof["kind"] == "cash"), "Cash kind/identity conflict")
            _require(key not in existing, "Ambiguous database resolved identity")
            provenance = proof.get("provenance")
            preserved_match = mode == "historical" and key in desired
            _require(provenance in ("source_managed", "manual")
                     or provenance == "unknown" and (pk in candidates or preserved_match),
                     "Unknown provenance")
            if table == HISTORY:
                _require(row.get("source_account_id") == scope["source_account_id"], "Database source-account conflict")
            managed = provenance == "source_managed"
            if managed:
                _require(proof.get("source_account_id") == scope["source_account_id"]
                         and _digest(proof.get("source_sha256")), "Unverified source ownership")
            if pk in candidates:
                candidate = candidates[pk]
                _require(candidate["row_sha256"] == proof["row_sha256"]
                         and candidate.get("source_sha256") == evidence["source_sha256"]
                         and candidate.get("source_account_id") == scope["source_account_id"], "Unbound historical candidate")
                managed = True
            if managed and proof["kind"] == "cash" and key not in desired:
                _require(row["currency"] in zeros, "Omitted cash is not proven zero")
            existing[key] = row, proof, managed
        after: list[dict] = []
        for key, (row, proof, managed) in existing.items():
            target = desired.get(key)
            if mode == "historical" and target is not None:
                _require((table, row["id"]) not in candidates, "Historical candidate is not an unsupported extra")
                after.append({"row": row, "ignore": []})
                continue
            if not managed:
                _require(target is None, "Manual provenance conflicts with source snapshot")
                after.append({"row": row, "ignore": []})
                continue
            if target is None:
                operations.append({"table": table, "action": "delete", "id": row["id"],
                                   "key": list(key), "before_sha256": proof["row_sha256"]})
                continue
            data = _payload(target, table, scope, evidence["numeric_scales"])
            changed = any(fingerprint([{field: row.get(field)}]) != fingerprint([{field: value}])
                          for field, value in data.items())
            if changed:
                operations.append({"table": table, "action": "update", "id": row["id"],
                                   "key": list(key), "before_sha256": proof["row_sha256"], "data": data})
            after.append({"row": {**row, **data}, "ignore": ["updated_at", "holding_pnl"] if changed else []})
        for key, target in desired.items():
            if key not in existing:
                if mode == "historical":
                    missing_source_rows.setdefault(table, []).append(list(key))
                    continue
                data = _payload(target, table, scope, evidence["numeric_scales"])
                operations.append({"table": table, "action": "insert", "key": list(key), "data": data})
                after.append({"row": data, "ignore": []})
        # The legacy unique key is NAME, not resolved identity/currency. Never UPSERT
        # through it: collisions (including manual rows) must block the entire batch.
        final_names = [item["row"]["name"] for item in after]
        _require(len(set(final_names)) == len(final_names), "Projected name collision")
        projected[table] = after
    _require(set(proofs) == seen_proofs and set(candidates) <= seen_proofs, "Out-of-scope row proof")
    plan = {"version": 2, "mode": mode,
            "policy": "historical_delete_only" if mode == "historical" else "source_snapshot_refresh",
            "scope": scope, "evidence": evidence, "missing_source_rows": missing_source_rows,
            "desired_rows": desired_rows, "ownership": ownership, "candidate_proofs": candidate_proofs,
            "before_sha256": dict(before_sha256), "operations": operations, "projected": projected}
    return {**plan, "plan_sha256": fingerprint([plan])}


def read_snapshot_rows(conn, *, account_code: str, as_of: date | str) -> dict[str, list[dict]]:
    """Read BOTH full account/day sets; caller owns the read transaction."""
    _require(_text(account_code), "Account required")
    day = _day(as_of)
    result = {}
    with conn.cursor(cursor_factory=RealDictCursor) as cur:
        for table in TABLES:
            cur.execute(sql.SQL("SELECT * FROM {} WHERE account_code=%s AND as_of=%s ORDER BY id LIMIT %s")
                        .format(sql.Identifier(SCHEMA, table)), (account_code, day, MAX_ROWS + 1))
            result[table] = [dict(row) for row in cur.fetchall()]
            _require(len(result[table]) <= MAX_ROWS, "Snapshot bound exceeded")
    return result


def read_snapshot_numeric_scales(conn) -> dict[str, dict[str, int]]:
    """Read existing schema only; no assumption that holdings/history share precision."""
    result: dict[str, dict[str, int]] = {table: {} for table in TABLES}
    with conn.cursor() as cur:
        cur.execute("""SELECT table_name,column_name,numeric_scale FROM information_schema.columns
            WHERE table_schema=%s AND table_name=ANY(%s) AND column_name=ANY(%s)""",
            (SCHEMA, list(TABLES), sorted(NUMBERS)))
        for table, field, scale in cur.fetchall():
            _require(type(scale) is int and 0 <= scale <= 10, "Unsupported numeric storage contract")
            result[table][field] = scale
    _require(all(set(result[table]) == NUMBERS for table in TABLES), "Incomplete numeric storage contract")
    return result


def _matches_projection(rows: dict[str, list[dict]], plan: dict) -> bool:
    for table in TABLES:
        current = {row["name"]: row for row in rows[table]}
        if len(current) != len(rows[table]) or len(current) != len(plan["projected"][table]):
            return False
        for item in plan["projected"][table]:
            expected = item["row"]
            actual = current.get(expected["name"])
            if actual is None:
                return False
            fields = set(expected) - set(item["ignore"])
            if fingerprint([{k: expected[k] for k in fields}]) != fingerprint([{k: actual.get(k) for k in fields}]):
                return False
    return True


def _authorize(plan: dict, authorization: dict | None) -> None:
    _require(isinstance(authorization, dict), "Explicit plan authorization required")
    auth = authorization or {}
    purpose = ("ibkr_complete_snapshot_sync" if plan["mode"] == "source_sync"
               else "ibkr_historical_snapshot_alignment")
    _require(auth.get("purpose") == purpose and auth.get("plan_sha256") == plan["plan_sha256"],
             "Authorization scope/digest mismatch")
    _require(_text(auth.get("reference")), "Authorization reference required")
    if plan["mode"] == "source_sync":
        _require(auth.get("source_owned") is True and not plan["candidate_proofs"], "Source-owned gate required")
        _require(auth.get("source_sha256") == plan["evidence"]["source_sha256"]
                 and auth.get("source_key") == plan["evidence"]["source_key"], "Source-owned gate mismatch")
    else:
        _require(_text(auth.get("approved_by")), "Historical approver required")
    try:
        issued, expires = (datetime.fromisoformat(auth[key]) for key in ("issued_at", "expires_at"))
        now = datetime.now(timezone.utc)
        _require(issued.tzinfo is not None and expires.tzinfo is not None and issued <= now < expires
                 and timedelta(0) < expires - issued <= timedelta(hours=24), "Expired/unbounded authorization")
    except (KeyError, TypeError, ValueError) as exc:
        raise AlignmentBlocked("Invalid authorization validity") from exc


def apply_snapshot_alignment(conn, plan: dict, *, source_bytes: bytes, dry_run: bool = True,
                             authorization: dict | None = None, within_transaction: bool = False) -> dict:
    """Validate/align atomically; never connect or invoke production automatically.

    Default dry-run starts a READ ONLY transaction and rolls it back. A live fresh
    connection is committed here; within_transaction uses a savepoint and NEVER
    commits the caller's transaction. Any failure rolls back the whole helper batch.
    Table locks prevent phantom extras/concurrent legacy UPSERTs during comparison.
    A repeated exact plan can return already_aligned, not claim a journaled apply;
    there is deliberately no schema/journal change in this helper.
    """
    _require(type(dry_run) is bool and type(within_transaction) is bool, "Explicit boolean modes required")
    body = {key: value for key, value in plan.items() if key != "plan_sha256"}
    _require(plan.get("version") == 2 and fingerprint([body]) == plan.get("plan_sha256"), "Plan changed/obsolete")
    expected_policy = "historical_delete_only" if plan.get("mode") == "historical" else "source_snapshot_refresh"
    _require(plan.get("mode") in ("historical", "source_sync") and plan.get("policy") == expected_policy,
             "Unsupported plan policy")
    if plan["mode"] == "historical":
        _require(all(op.get("action") == "delete" for op in plan["operations"]), "Historical apply is deletion-only")
    _scope(plan["evidence"])
    _require(isinstance(source_bytes, bytes) and len(source_bytes) <= MAX_XML_BYTES
             and hashlib.sha256(source_bytes).hexdigest() == plan["evidence"]["source_sha256"], "Source bytes changed")
    if not dry_run:
        _authorize(plan, authorization)
    status = conn.get_transaction_status()
    _require(not conn.autocommit and status == (TRANSACTION_STATUS_INTRANS if within_transaction else TRANSACTION_STATUS_IDLE),
             "Non-autocommit connection with explicit transaction ownership required")
    savepoint = "ibkr_alignment_" + plan["plan_sha256"][:16]
    started = False
    try:
        with conn.cursor() as cur:
            if within_transaction:
                cur.execute(sql.SQL("SAVEPOINT {}").format(sql.Identifier(savepoint)))
            else:
                cur.execute("BEGIN ISOLATION LEVEL REPEATABLE READ" + (" READ ONLY" if dry_run else ""))
            started = True
            cur.execute("SHOW lock_timeout")
            old_lock_timeout = cur.fetchone()[0]
            cur.execute("SHOW statement_timeout")
            old_statement_timeout = cur.fetchone()[0]
            cur.execute("SET LOCAL lock_timeout = '2000ms'")
            cur.execute("SET LOCAL statement_timeout = '15000ms'")
            if not dry_run:
                if within_transaction:
                    cur.execute("SHOW transaction_isolation")
                    _require(cur.fetchone()[0] == "read committed", "Nested apply requires READ COMMITTED to exclude stale phantoms")
                cur.execute(sql.SQL("LOCK TABLE {} IN SHARE ROW EXCLUSIVE MODE").format(
                    sql.SQL(",").join(sql.Identifier(SCHEMA, table) for table in TABLES)))
            _require(read_snapshot_numeric_scales(conn) == plan["evidence"]["numeric_scales"], "Numeric schema drift")
            current = read_snapshot_rows(conn, account_code=plan["scope"]["account_code"], as_of=plan["scope"]["as_of"])
            if {table: fingerprint(current[table]) for table in TABLES} != plan["before_sha256"]:
                _require(_matches_projection(current, plan), "Before-state drift/partial apply")
                result = {"status": "already_aligned", "changed": 0, "dry_run": dry_run}
            else:
                rebuilt = plan_snapshot_alignment(evidence=plan["evidence"], desired_rows=plan["desired_rows"],
                    before_rows=current, before_sha256=plan["before_sha256"], ownership=plan["ownership"],
                    mode=plan["mode"], candidate_proofs=plan["candidate_proofs"])
                _require(rebuilt["plan_sha256"] == plan["plan_sha256"], "Plan does not match evidence")
                if not dry_run:
                    # Delete extras first; updates/inserts cannot consume legacy name conflicts.
                    for action in ("delete", "update", "insert"):
                        for op in plan["operations"]:
                            if op["action"] == action:
                                _write(cur, op, plan["scope"])
                    after = read_snapshot_rows(conn, account_code=plan["scope"]["account_code"], as_of=plan["scope"]["as_of"])
                    _require(_matches_projection(after, plan), "Post-write snapshot verification failed")
                    _authorize(plan, authorization)
                result = {"status": "dry_run" if dry_run else "applied" if plan["operations"] else "already_aligned",
                          "changed": 0 if dry_run else len(plan["operations"]), "dry_run": dry_run}
            if within_transaction:
                cur.execute("SELECT set_config('lock_timeout',%s,true),set_config('statement_timeout',%s,true)",
                            (old_lock_timeout, old_statement_timeout))
            if within_transaction:
                cur.execute(sql.SQL("RELEASE SAVEPOINT {}").format(sql.Identifier(savepoint)))
        if not within_transaction:
            conn.rollback() if dry_run else conn.commit()
        return {**result, "planned_changes": len(plan["operations"]), "plan_sha256": plan["plan_sha256"],
                "policy": plan["policy"], "missing_source_rows": plan["missing_source_rows"],
                "commit_owned_by_caller": within_transaction}
    except BaseException:
        if not started:
            raise
        if within_transaction:
            with conn.cursor() as cur:
                cur.execute(sql.SQL("ROLLBACK TO SAVEPOINT {}").format(sql.Identifier(savepoint)))
                cur.execute(sql.SQL("RELEASE SAVEPOINT {}").format(sql.Identifier(savepoint)))
        else:
            conn.rollback()
        raise


def _write(cur, op: dict, scope: dict) -> None:
    table = sql.Identifier(SCHEMA, op["table"])
    where = sql.SQL(" WHERE id=%s AND account_code=%s AND as_of=%s")
    params = (op.get("id"), scope["account_code"], scope["as_of"])
    if op["action"] == "delete":
        cur.execute(sql.SQL("DELETE FROM {} ").format(table) + where, params)
    else:
        fields = list(op["data"])
        values = tuple(op["data"][field] for field in fields)
        if op["action"] == "insert":
            cur.execute(sql.SQL("INSERT INTO {} ({}) VALUES ({})").format(table,
                        sql.SQL(",").join(map(sql.Identifier, fields)),
                        sql.SQL(",").join(sql.Placeholder() for _ in fields)), values)
        else:
            assignments = sql.SQL(",").join(sql.SQL("{}=%s").format(sql.Identifier(field)) for field in fields)
            cur.execute(sql.SQL("UPDATE {} SET {},updated_at=NOW()").format(table, assignments) + where,
                        values + params)
    _require(cur.rowcount == 1, "Concurrent row-count change")
