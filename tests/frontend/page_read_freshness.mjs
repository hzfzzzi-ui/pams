import assert from 'node:assert/strict';
import {createPageRead, watchPageRead} from '../../frontend/public/assets/js/shared/page_read.js';

const host = new EventTarget();
let clock = 0, path = '/same', version = 1;
const requests = [];
const read = createPageRead(() => path, {host, now: () => clock, maxAge: 100,
  read: (url, options) => {
    let resolve, reject;
    const promise = new Promise((yes, no) => { resolve = yes; reject = no; });
    requests.push({url, options, resolve, reject});
    return promise;
  }});
const first = read();
assert.equal(read(), first, 'concurrent list and card share one request');
requests[0].resolve({version});
await first;
assert.equal(await read(), await first, 'briefly reuse settled data for startup consumers');
clock = 101;
const fresh = read();
assert.notEqual(fresh, first);
requests[1].resolve({version: ++version});
assert.equal((await fresh).version, 2);
path = '/other';
const other = read();
requests[2].reject(new Error('temporary'));
await assert.rejects(other, /temporary/);
const retry = read();
assert.equal(requests.length, 4, 'failed promise must not poison the document');
requests[3].resolve({version: 3});
await retry;
clock = 202;
const departing = read();
host.dispatchEvent(new Event('pagehide'));
assert.equal(requests[4].options.signal.aborted, true);
const restored = read();
requests[4].reject(Object.assign(new Error('cancelled'), {name: 'AbortError'}));
await assert.rejects(departing, {name: 'AbortError'});
assert.equal(read(), restored, 'old cancellation cannot clear the restored read');
requests[5].resolve({version: 4});
await restored;
assert.ok(requests.every(r => r.options.cache === false));

const doc = new EventTarget();
doc.visibilityState = 'hidden';
const timers = [], listeners = [];
const scope = {active: true, timeout: fn => {if (scope.active) timers.push(fn);},
  listen: (target, type, fn) => {target.addEventListener(type, fn); listeners.push(() => target.removeEventListener(type, fn));}};
let calls = 0, finish;
watchPageRead(scope, {document: doc}, () => {calls++; return new Promise(resolve => {finish = resolve;});});
await timers.shift()();
assert.equal(calls, 0, 'background tabs do not poll');
doc.visibilityState = 'visible';
doc.dispatchEvent(new Event('visibilitychange'));
doc.dispatchEvent(new Event('visibilitychange'));
assert.equal(calls, 1, 'resuming does not stack refreshes');
finish();
await new Promise(resolve => setImmediate(resolve));
const tick = timers.shift()();
assert.equal(calls, 2, 'open page refreshes without navigation');
finish();
await tick;
scope.active = false;
listeners.forEach(remove => remove());
await timers.shift()();
assert.equal(calls, 2, 'disposed controllers cannot refresh');
console.log('Shared page freshness: coalescing, expiry, key changes, retry, restore, hidden and disposed lifecycle passed.');
