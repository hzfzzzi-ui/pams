-- Slim fact contracts for the redesigned source model, not an in-place upgrade.
CREATE TABLE public.pams_cashflow_fact (
    cashflow_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_code VARCHAR(80) NOT NULL REFERENCES public.pams_accounts(account_code),
    event_date DATE NOT NULL,
    posting_date DATE,
    amount NUMERIC(20,4) NOT NULL CHECK (amount::text NOT IN ('NaN','Infinity','-Infinity')),
    currency VARCHAR(10) NOT NULL CHECK (length(btrim(currency)) > 0),
    counterparty TEXT,
    summary TEXT,
    description TEXT,
    source_item_id UUID NOT NULL REFERENCES public.source_items(source_item_id) ON DELETE RESTRICT,
    fact_role VARCHAR(40) NOT NULL CHECK (length(btrim(fact_role)) > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (source_item_id, fact_role)
);
CREATE INDEX idx_cashflow_fact_account_date ON public.pams_cashflow_fact(account_code,event_date DESC);

CREATE TABLE public.pams_investment_trade_fact (
    trade_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_code VARCHAR(80) NOT NULL REFERENCES public.pams_accounts(account_code),
    broker VARCHAR(80), portfolio_code VARCHAR(120),
    trade_date DATE NOT NULL, trade_time TIMESTAMP, settle_date DATE,
    asset_id VARCHAR(120) REFERENCES public.pams_asset_master(asset_id) ON DELETE SET NULL,
    symbol VARCHAR(120), name VARCHAR(240), market VARCHAR(80), currency VARCHAR(10) NOT NULL CHECK (length(btrim(currency)) > 0),
    trade_type VARCHAR(40) NOT NULL CHECK (trade_type IN ('buy','sell','deposit','withdraw',
        'fund_subscription','fund_redemption','dividend','interest','coupon','fee','tax','fx_conversion',
        'corporate_action','split','transfer_in_kind','transfer_out_kind','position_adjustment','unknown')),
    side VARCHAR(40),
    quantity NUMERIC(28,10), price NUMERIC(28,10), gross_amount NUMERIC(28,10),
    fee_amount NUMERIC(28,10), fee_currency VARCHAR(3), tax_amount NUMERIC(28,10),
    net_cash NUMERIC(28,10), execution_status TEXT, notes TEXT,
    source_item_id UUID NOT NULL REFERENCES public.source_items(source_item_id) ON DELETE RESTRICT,
    fact_role VARCHAR(40) NOT NULL CHECK (length(btrim(fact_role)) > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (fee_currency IS NULL OR fee_currency ~ '^[A-Z]{3}$'),
    CHECK (quantity IS NULL OR quantity::text NOT IN ('NaN','Infinity','-Infinity')),
    CHECK (price IS NULL OR price::text NOT IN ('NaN','Infinity','-Infinity')),
    CHECK (gross_amount IS NULL OR gross_amount::text NOT IN ('NaN','Infinity','-Infinity')),
    CHECK (fee_amount IS NULL OR fee_amount::text NOT IN ('NaN','Infinity','-Infinity')),
    CHECK (tax_amount IS NULL OR tax_amount::text NOT IN ('NaN','Infinity','-Infinity')),
    CHECK (net_cash IS NULL OR net_cash::text NOT IN ('NaN','Infinity','-Infinity')),
    UNIQUE (source_item_id, fact_role)
);
CREATE INDEX idx_trade_fact_account_date ON public.pams_investment_trade_fact(account_code,trade_date DESC);

-- A fact is linked only to a reviewed source for the same account.
CREATE FUNCTION public.redesigned_fact_source_guard() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE source_account TEXT; item_status TEXT;
BEGIN
    SELECT r.account_code, i.review_status INTO source_account, item_status
    FROM public.source_items i JOIN public.source_records r ON r.source_id=i.source_id
    WHERE i.source_item_id=NEW.source_item_id FOR SHARE OF i, r;
    IF source_account IS DISTINCT FROM NEW.account_code OR item_status IS DISTINCT FROM 'confirmed' THEN
        RAISE EXCEPTION 'fact requires reviewed source for same account' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER redesigned_cashflow_source_guard BEFORE INSERT OR UPDATE OF account_code, source_item_id
    ON public.pams_cashflow_fact FOR EACH ROW EXECUTE FUNCTION public.redesigned_fact_source_guard();
CREATE TRIGGER redesigned_trade_source_guard BEFORE INSERT OR UPDATE OF account_code, source_item_id
    ON public.pams_investment_trade_fact FOR EACH ROW EXECUTE FUNCTION public.redesigned_fact_source_guard();

-- A transaction may stage facts while publishing, but cannot commit them against a draft.
CREATE FUNCTION public.redesigned_published_source_required() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE source_status TEXT; item_status TEXT;
BEGIN
    SELECT r.status, i.review_status INTO source_status, item_status
    FROM public.source_items i JOIN public.source_records r ON r.source_id=i.source_id
    WHERE i.source_item_id=NEW.source_item_id;
    IF source_status IS DISTINCT FROM 'published' OR item_status IS DISTINCT FROM 'confirmed' THEN
        RAISE EXCEPTION 'fact requires published confirmed source' USING ERRCODE='23514';
    END IF;
    RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER redesigned_cashflow_published_source
    AFTER INSERT OR UPDATE ON public.pams_cashflow_fact DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION public.redesigned_published_source_required();
CREATE CONSTRAINT TRIGGER redesigned_trade_published_source
    AFTER INSERT OR UPDATE ON public.pams_investment_trade_fact DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION public.redesigned_published_source_required();
